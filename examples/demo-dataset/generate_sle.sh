#!/usr/bin/env bash
#
# Generates a synthetic three-year lupus course for the **disease-profile**
# rule engine (patient: 李静, 女, SLE + class IV lupus nephritis, 2024-2026,
# four hospitals). Deliberately a *different patient* from generate.sh's
# 张建国 — piling an immune disease onto him would shift every existing
# corpus assertion in packages/parser/tests.
#
# Output: examples/demo-dataset/corpus-sle/  (NOT imported into any vault here)
# The checked-in copy lives in packages/profile/testdata/corpus/ and is lifted
# out of the heredocs below by extract_fixtures.py — never hand-edit it.
#
# Text only: the profile tests read text, and the .txt tier needs no macOS
# tooling, so this script runs anywhere (unlike generate.sh, which shells out
# to cupsfilter/Pillow for the PDF and scan tiers).
#
# Idempotent: every run overwrites the same file names.
#
# Usage:  bash examples/demo-dataset/generate_sle.sh

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CORPUS_DIR="$SCRIPT_DIR/corpus-sle"

mkdir -p "$CORPUS_DIR"

echo "== MedMe synthetic SLE course generator =="
echo "Corpus dir: $CORPUS_DIR"

# write_txt <relative-filename>   (content piped in via stdin)
write_txt() {
  local out="$CORPUS_DIR/$1"
  cat > "$out"
  echo "  [txt] $1 ($(wc -c < "$out" | tr -d ' ') bytes)"
}

echo ""
echo "-- Generating records --"

